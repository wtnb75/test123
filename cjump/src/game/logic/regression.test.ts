describe('unchanged game parameters', () => {
    it('keeps the fixed gameplay constants at the spec values', () => {
        expect(JUMP_DURATION_MS).toBe(400);
        expect(CHARACTER_PIXEL_SPEED_PER_SEC).toBe(130);
        expect(EDGE_LINE_WIDTH).toBe(6);
        expect(COLLISION_TOLERANCE).toBe(3);
        expect(CIRCLE_WARNING_MS).toBe(500);
        expect(STAGE_COUNT).toBe(10);
    });

    it.each(SPEC_TABLE)('keeps the stage $stage difficulty values of the spec table', (row) => {
        expect(getDifficultyParams(row.stage)).toEqual({
            thetaMaxDeg: row.theta,
            waypointCount: row.waypoints,
            circleSpawnIntervalMs: row.interval,
            circleGrowthSpeedPxPerSec: row.growth
        });
    });

    it.each(Object.keys(ROUTES_BEFORE).map(Number))('keeps the stage %i route identical to before the extension', (stage) => {
        const expected = ROUTES_BEFORE[stage];
        const actual = stageRoute(stage);
        expect(actual).toHaveLength(expected.length);
        actual.forEach((p, i) => {
            expect(p.x).toBeCloseTo(expected[i][0], 6);
            expect(p.y).toBeCloseTo(expected[i][1], 6);
        });
    });
});
